    ("Область", "класс", "таблица oblast: строка → экземпляр"),
    ("Район", "класс", "таблица rayon: строка → экземпляр"),
    ("Месторождение", "класс", "таблица field: строка → экземпляр"),
    ("Пласт", "класс", "таблица horizon: строка → экземпляр (индекс пласта и месторождение → подпись)"),
    ("Залежь", "класс", "таблица deposit: строка → экземпляр"),
    ("ЗонаНефтегазонакопления", "класс", "в БД нет таблицы: класс есть в онтологии, экземпляров пока нет"),
    ("Публикация", "класс", "таблица publication: строка → экземпляр"),
    ("Исследование", "класс", "суперкласс: объединяет таблицу research_type"),
    ("входитВ", "объектное свойство", "внешние ключи «ребёнок → родитель»: oblast.province_id, rayon.oblast_id, field.rayon_id, horizon.field_id, deposit.horizon_id; транзитивно"),
    ("содержит", "объектное свойство", "обратное к входитВ: в БД не хранится, выводится рассуждателем"),
    ("имеетМесторождение", "объектное свойство", "тот же внешний ключ field.rayon_id, со стороны района"),
