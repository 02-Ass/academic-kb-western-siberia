_TYPE_CLASSES = ["Геологическое", "Геофизическое", "Гидрогеологическое", "Геодинамическое", "Геокриологическое", "Разработка"]
_EXT_ROWS = [
    ("DOI", "свойство-данные (расширение)", "столбец publication.doi"),
    ("описание", "свойство-данные (расширение)", "столбец description у province, oblast, rayon, field"),
    ("годОткрытия", "свойство-данные (расширение)", "столбец field.discovery_date (год)"),
    ("координаты", "свойство-данные (расширение)", "столбец field.coordinates"),
    ("записьБД", "свойство-данные (расширение)", "ключ записи БД у каждого экземпляра: «таблица:первичный ключ»"),
    ("имеетПубликацию", "объектное свойство (расширение)", "обратное к относитсяКОбъекту, в БД не хранится"),
]


def mapping_rows(state: OntologyState) -> List[dict]:
    rows = [{"element": e, "kind": k, "db": d, "origin": "наша онтология"} for e, k, d in _BASE_ROWS]
    used = {}
    for info in state.reg.types.values():
        used.setdefault(V.short(info["class_iri"]), []).append(info["name"])
    for cls in _TYPE_CLASSES:
        names = used.get(cls)
        db = (f"таблица research_type: строка «{'», «'.join(names)}» → экземпляр {cls}_исследование" if names
              else "в таблице research_type нет такой строки: класс есть в онтологии, экземпляров пока нет")
        rows.append({"element": cls, "kind": "класс (подкласс Исследования)", "db": db, "origin": "наша онтология"})
    rows += [{"element": e, "kind": k, "db": d, "origin": "расширение приложения"} for e, k, d in _EXT_ROWS]
    for name in state.base.extension_classes:
        rows.append({"element": name, "kind": "класс (расширение)", "db": f"таблица research_type: строка «{name}»; в онтологии такого класса нет",
                     "origin": "расширение приложения"})
    return rows


def base_entities(state: OntologyState) -> List[str]:
    """Короткие имена всех классов и свойств нашего файла (для проверки полноты таблицы)."""
    return sorted(V.short(i) for i in (state.base.classes | state.base.object_props | state.base.data_props))
